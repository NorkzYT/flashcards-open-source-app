#!/bin/sh
# One-shot RustFS initialisation for the standalone stack, run on every `up` (idempotent) with the
# image's own `rc` client:
#   - the media bucket, private (no anonymous access), with the hosted bucket's expiry rules
#     (infra/aws/lib/media-assets.ts);
#   - a bucket-scoped application user whose secret comes from secrets/objectstore_media_secret_key.
# Credentials reach `rc` through RC_HOST_* in this process only, never as command arguments.
set -eu

fail() {
  echo "objectstore-init: $*" >&2
  exit 1
}

read_secret() {
  value="$(cat "$1")"
  [ -n "$value" ] || fail "secret file $1 is empty"
  case "$value" in
    *[!0-9a-f]*) fail "secret file $1 must contain the hex value generated by setup.sh" ;;
  esac
  printf '%s' "$value"
}

: "${OBJECTSTORE_ENDPOINT:?OBJECTSTORE_ENDPOINT is required}"
: "${MEDIA_BUCKET:?MEDIA_BUCKET is required}"
printf '%s' "$MEDIA_BUCKET" | grep -Eq '^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$' \
  || fail "MEDIA_BUCKET must be 3-63 lowercase letters, digits or hyphens"
ENDPOINT_AUTHORITY="${OBJECTSTORE_ENDPOINT#http://}"

ROOT_ACCESS_KEY="$(read_secret /run/secrets/objectstore_root_access_key)"
ROOT_SECRET_KEY="$(read_secret /run/secrets/objectstore_root_secret_key)"
MEDIA_ACCESS_KEY="$(read_secret /run/secrets/objectstore_media_access_key)"
read_secret /run/secrets/objectstore_media_secret_key >/dev/null
[ "$MEDIA_ACCESS_KEY" != "$ROOT_ACCESS_KEY" ] || fail "the media and root access keys must differ"

RC_CONFIG_DIR="$(mktemp -d /tmp/rc.XXXXXX)"
export RC_CONFIG_DIR
RC_HOST_root="http://${ROOT_ACCESS_KEY}:${ROOT_SECRET_KEY}@${ENDPOINT_AUTHORITY}"
export RC_HOST_root
unset ROOT_SECRET_KEY

# v2 adds ListMultipartUploadParts. Attaching sets the user's whole policy mapping (RustFS 1.0.6), so
# an upgraded instance drops v1 here.
POLICY_NAME="nibomo-media-v2"
WORK_DIR="$(mktemp -d /tmp/init.XXXXXX)"

rc --quiet bucket create --ignore-existing "root/${MEDIA_BUCKET}"
rc --quiet bucket anonymous set private "root/${MEDIA_BUCKET}"
echo "objectstore-init: bucket ${MEDIA_BUCKET} present, anonymous access private"

# Expiry for staging prefixes only; promoted media is never expired by the store.
ensure_expiry() {
  prefix="$1"
  days="$2"
  if rc --json bucket lifecycle rule list "root/${MEDIA_BUCKET}" 2>/dev/null \
      | jq -e --arg prefix "$prefix" '[.. | strings | select(. == $prefix)] | length > 0' >/dev/null; then
    return 0
  fi
  rc --quiet bucket lifecycle rule add "root/${MEDIA_BUCKET}" --prefix "$prefix" --expiry-days "$days"
  echo "objectstore-init: expiry ${days}d on ${prefix}"
}
ensure_expiry "media/uploads/" 7
ensure_expiry "chat-files/uploads/" 1
ensure_expiry "workspace-exports/" 1

# Object read/write/delete inside the one bucket, plus ListBucket on it so a missing key answers
# 404 (the blob-cleanup and chat-file contracts depend on that). ListMultipartUploadParts: multipart
# completion and its reconciliation list the uploaded parts (as the hosted IAM grants). No bucket
# administration, no other bucket, no IAM. A changed policy gets a new versioned name.
cat > "${WORK_DIR}/policy.json" <<POLICY
{
  "Version": "2012-10-17",
  "Statement": [
    {
      "Effect": "Allow",
      "Action": ["s3:ListBucket", "s3:GetBucketLocation"],
      "Resource": ["arn:aws:s3:::${MEDIA_BUCKET}"]
    },
    {
      "Effect": "Allow",
      "Action": [
        "s3:GetObject", "s3:PutObject", "s3:DeleteObject",
        "s3:AbortMultipartUpload", "s3:ListMultipartUploadParts"
      ],
      "Resource": ["arn:aws:s3:::${MEDIA_BUCKET}/*"]
    }
  ]
}
POLICY
if ! rc --quiet admin policy info root "$POLICY_NAME" >/dev/null 2>&1; then
  rc --quiet admin policy create root "$POLICY_NAME" "${WORK_DIR}/policy.json"
  echo "objectstore-init: created policy ${POLICY_NAME}"
fi

if ! rc --quiet admin user info root "$MEDIA_ACCESS_KEY" >/dev/null 2>&1; then
  # Created with a throwaway secret, then set from the secret file below, so the real secret is
  # never a process argument.
  rc --quiet admin user add root "$MEDIA_ACCESS_KEY" "$(od -An -N20 -tx1 /dev/urandom | tr -d ' \n')"
  echo "objectstore-init: created application user"
fi
rc --quiet admin user passwd root "$MEDIA_ACCESS_KEY" --password-file /run/secrets/objectstore_media_secret_key
if ! rc --json admin user info root "$MEDIA_ACCESS_KEY" \
    | jq -e --arg policy "$POLICY_NAME" '[.. | strings | select(split(",") | index($policy))] | length > 0' >/dev/null; then
  rc --quiet admin policy attach root "$POLICY_NAME" --user "$MEDIA_ACCESS_KEY"
  echo "objectstore-init: attached ${POLICY_NAME}"
fi

# Prove the application credential works for its bucket and cannot administer the store.
RC_HOST_app="http://${MEDIA_ACCESS_KEY}:$(read_secret /run/secrets/objectstore_media_secret_key)@${ENDPOINT_AUTHORITY}"
export RC_HOST_app
unset RC_HOST_root
rc --quiet object list "app/${MEDIA_BUCKET}/media/blobs/nibomo-init-probe/" >/dev/null \
  || fail "the application user cannot list its bucket"
if rc --quiet admin user ls app >/dev/null 2>&1; then
  fail "the application user can administer users; refusing to continue"
fi
echo "objectstore-init: application user verified (bucket access, no IAM administration)"
